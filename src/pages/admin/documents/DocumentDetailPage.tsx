import { useEffect, useState } from 'react'
import { useQuery } from '@tanstack/react-query'
import { Link, useParams } from 'react-router-dom'
import { Badge, Button, Card, EmptyState, InfoNote, SectionTitle, Skeleton } from '@/components/ui/base'
import { DefinitionList } from '@/components/data-display/fields'
import { documentService } from '@/services/documents'
import { useAuth } from '@/app/auth-context'
import { useHeader, PageHeaderBar } from '@/components/layout/page-header'
import type { CompanyDocument } from '@/types/domain'
import { formatNptDate } from '@/utils/npt'
import { formatDocSize, docCategoryTone } from '@/modules/documents/doc-format'

export function DocumentDetailPage() {
  const { documentId } = useParams()
  const { session } = useAuth()
  useHeader('Document', [{ label: 'Workspace' }, { label: 'Documents', to: '/documents' }, { label: documentId ?? '' }])

  const doc = useQuery({
    queryKey: ['documents', 'detail', documentId, session?.role],
    queryFn: () => documentService.get(documentId ?? '', session),
    enabled: !!documentId,
  })

  const [downloadNote, setDownloadNote] = useState(false)
  useEffect(() => {
    if (!downloadNote) return
    const t = window.setTimeout(() => setDownloadNote(false), 4000)
    return () => window.clearTimeout(t)
  }, [downloadNote])

  const d = doc.data

  if (doc.isLoading) return <div className="space-y-3"><Skeleton className="h-8 w-80" /><Skeleton className="h-48 w-full" /></div>
  if (doc.isError || !d) return <EmptyState title="Document not found" action={<Link to="/documents"><Button variant="secondary" size="sm">Back to documents</Button></Link>} />

  return (
    <div className="space-y-4">
      <PageHeaderBar title={d.name} description={`${d.category} · owned by ${d.owner} · updated ${formatNptDate(`${d.updatedAt}T00:00:00Z`)}`}>
        <Badge tone={docCategoryTone(d.category)}>{d.category}</Badge>
        <Button variant="secondary" onClick={() => setDownloadNote(true)}>
          Download
        </Button>
      </PageHeaderBar>

      {downloadNote ? (
        <InfoNote tone="orange">
          Downloads are served by the backend via short-lived signed URLs — nothing is stored or generated by the frontend build.
        </InfoNote>
      ) : null}

      <div className="grid gap-4 lg:grid-cols-3">
        <Card className="p-6 lg:col-span-2">
          <SectionTitle title="Summary" />
          <p className="mt-3 max-w-2xl text-sm leading-relaxed text-ink-deep">{d.summary}</p>
          <div className="mt-6 border-t border-line pt-4">
            <SectionTitle title="Viewer" description="The file preview comes from the backend document streams; it is intentionally blank here." />
            <div className="mt-3 flex h-64 flex-col items-center justify-center gap-2 rounded-xl border border-dashed border-line bg-canvas text-center">
              <p className="text-sm font-medium text-ink">{d.name}</p>
              <p className="text-xs text-muted">{formatDocSize(d.sizeKb)} · {d.category}</p>
              <p className="px-4 text-xs text-muted">Secure preview requires the file-storage service.</p>
            </div>
          </div>
        </Card>

        <Card className="p-6">
          <SectionTitle title="Metadata" />
          <div className="mt-4">
            <Metadata d={d} />
          </div>
          <p className="mt-4 border-t border-line pt-3 text-xs text-muted">
            Visibility “{d.visibility}” is enforced server-side. This page is UX only.
          </p>
        </Card>
      </div>
    </div>
  )
}

function Metadata({ d }: { d: CompanyDocument }) {
  return (
    <DefinitionList
      rows={[
        { label: 'Category', value: d.category },
        { label: 'Owner', value: d.owner },
        { label: 'Uploaded by', value: d.uploadedBy },
        { label: 'Visibility', value: d.visibility },
        { label: 'Size', value: formatDocSize(d.sizeKb) },
        { label: 'Updated', value: formatNptDate(`${d.updatedAt}T00:00:00Z`) },
      ]}
    />
  )
}
