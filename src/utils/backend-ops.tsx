import { useEffect, useState } from 'react'
import type { ReactNode } from 'react'
import { API_MODE } from '@/services/api/client'
import { InfoNote } from '@/components/ui/base'

type Listener = (message: string | null) => void

let currentNotice: string | null = null
const listeners = new Set<Listener>()
let autoHideTimer: number | null = null

export function publishBackendNotice(message: string): void {
  currentNotice = message
  if (autoHideTimer) window.clearTimeout(autoHideTimer)
  listeners.forEach((l) => l(currentNotice))
  autoHideTimer = window.setTimeout(() => {
    currentNotice = null
    listeners.forEach((l) => l(null))
  }, 5000)
}

export function clearBackendNotice(): void {
  if (autoHideTimer) window.clearTimeout(autoHideTimer)
  currentNotice = null
  listeners.forEach((l) => l(null))
}

/**
 * Buttons that would trigger backend-generated artifacts (CSV/XLSX/PDF exports,
 * uploads, downloads) show an explanatory in-app notice instead of fabricating
 * files client-side. Nothing is stored or generated in the frontend build.
 */
export function notifyBackendScoped(action: string): void {
  publishBackendNotice(`${action} is generated by the FastAPI backend with role-based scoping. The demo build performs nothing client-side.`)
}

export function notifyUpload(name: string, limits: string): void {
  publishBackendNotice(`${name} upload is a backend multipart endpoint (${limits}). Uploading stays disabled in the frontend build until the file API is live.`)
}

export function BackendOpBanner(): ReactNode {
  const [notice, setNotice] = useState<string | null>(currentNotice)

  useEffect(() => {
    listeners.add(setNotice)
    return () => {
      listeners.delete(setNotice)
    }
  }, [])

  if (!notice) return null

  return (
    <div className="mb-4" role="status" aria-live="polite">
      <InfoNote tone="orange">
        <span className="flex flex-wrap items-center justify-between gap-3">
          <span>{notice}</span>
          <button
            type="button"
            onClick={clearBackendNotice}
            className="text-xs font-semibold text-ink underline hover:text-brand-600"
          >
            Dismiss
          </button>
        </span>
      </InfoNote>
    </div>
  )
}

/** Shared demo-mode caption (single line used on list pages). */
export const demoModeNote: ReactNode | null = API_MODE === 'demo'
  ? (
      <p className="text-xs text-muted" role="note">
        Demo data — changes are session-only and are never persisted.
      </p>
    )
  : null
