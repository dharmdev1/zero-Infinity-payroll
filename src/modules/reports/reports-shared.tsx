import type { ReactNode } from 'react'
import { InfoNote } from '@/components/ui/base'
import { publishBackendNotice } from '@/utils/backend-ops'

/** Banner shown on report pages: exports are backend endpoints, not client-side files. */
export function ReportsExportNote(): ReactNode {
  return (
    <InfoNote tone="orange">
      Reports are read-only views of stored data. CSV/XLSX/PDF exports call backend endpoints — the buttons below explain this instead of
      fabricating files in the browser.
    </InfoNote>
  )
}

export function notifyReportExport(name: string): void {
  publishBackendNotice(`${name} export will be generated by the reporting API once it is connected. No client-side exports.`)
}

/** Month start derived from the demo anchor date, e.g. "2026-10-01". */
export function monthStartFromAnchor(anchor: string): string {
  return `${anchor.slice(0, 7)}-01`
}
